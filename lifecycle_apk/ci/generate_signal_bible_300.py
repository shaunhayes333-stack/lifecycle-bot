#!/usr/bin/env python3
"""Compile the owner's handwritten signal bible into a read-only Kotlin research catalog.

The Markdown is the only authored source. This generator never creates live
entry/exit predicates: those require separately proven, venue-correct features.
Run with --check in CI to prevent drift between the book and the APK.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/AATE_Meme_Signal_Bible_300.md"
OUTPUT = ROOT / "lifecycle_apk/app/src/main/kotlin/com/lifecyclebot/engine/truth/SignalBible300.kt"
HEADING = re.compile(r"^### ([A-Z]{1,2})\. (.+?) — [ST]\d{3}–[ST]\d{3}$")
ENTRY = re.compile(r"^- \*\*([ST]\d{3}) — (.+?)\*\* (.+)$")
SIGNAL_ID = re.compile(r"\bS\d{3}\b")


def literal(value: str) -> str:
    # Kotlin's ordinary quoted literals understand JSON escapes. Also escape
    # Kotlin interpolation ($foo / ${foo}); the original prose is never code.
    return json.dumps(value, ensure_ascii=False).replace("$", r"\$")


def extract(source: str) -> list[dict]:
    items = []
    family = ""
    for line in source.splitlines():
        heading = HEADING.match(line)
        if heading:
            family = heading.group(1)
            continue
        match = ENTRY.match(line)
        if not match:
            continue
        ident, title, detail = match.groups()
        if not family:
            raise ValueError(f"Orphan definition: {ident}")
        kind = (
            "EVIDENCE" if ident.startswith("S") else
            "NO_LONG" if ident in {"T276", "T288", "T294"} else
            "MANAGEMENT" if int(ident[1:]) >= 295 else
            "ENTRY"
        )
        item = {
            "id": ident, "family": family, "title": title,
            "guidance": detail, "kind": kind,
            "refs": sorted(set(SIGNAL_ID.findall(detail))) if ident.startswith("T") else [],
        }
        if ident.startswith("S") and ("ON:" not in detail or "OFF:" not in detail):
            raise ValueError(f"Missing ON/OFF lifecycle: {ident}")
        if ident.startswith("T") and any(label not in detail for label in ("**Trigger", "**Fail", "**Manage")):
            raise ValueError(f"Missing Trigger/Fail/Manage lifecycle: {ident}")
        items.append(item)

    expected = [f"S{i:03}" for i in range(1, 241)] + [f"T{i:03}" for i in range(241, 301)]
    ids = [item["id"] for item in items]
    if ids != expected:
        raise ValueError(f"Expected consecutive S001–S240/T241–T300; got {len(ids)} entries, first mismatch: " +
                         str(next(((a, b) for a, b in zip(ids, expected) if a != b), None)))
    family_sizes = {name: sum(item["family"] == name for item in items) for name in set(i["family"] for i in items)}
    signal_families = {item["family"] for item in items[:240]}
    setup_families = {item["family"] for item in items[240:]}
    if len(signal_families) != 20 or len(setup_families) != 10 or signal_families & setup_families:
        raise ValueError(f"Expected 20 signal and 10 setup families: {family_sizes}")
    if any(family_sizes[k] != 12 for k in signal_families) or any(family_sizes[k] != 6 for k in setup_families):
        raise ValueError(f"Family size drift: {family_sizes}")
    all_signals = set(expected[:240])
    for item in items[240:]:
        if not item["refs"] or not set(item["refs"]) <= all_signals:
            raise ValueError(f"Setup has missing or unknown evidence: {item['id']}")
    return items


def generate(source: str, items: list[dict]) -> str:
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    lines = [
        "// Generated from docs/AATE_Meme_Signal_Bible_300.md by ci/generate_signal_bible_300.py.",
        "// Do not edit this file directly. All hypotheses are UNVALIDATED and grant no live authority.",
        "package com.lifecyclebot.engine.truth",
        "",
        "/** The owner's 240 handwritten signal definitions and 60 combined research playbooks.",
        " * Never a second entry gate, model override, or position-exit authority.",
        " * LLM research may cite a recipe only after the grading engine tests a representable hypothesis.",
        " */",
        "object SignalBible300 {",
        f'    const val SOURCE_SHA256 = "{digest}"',
        "    const val LIVE_AUTHORITY = false",
        "    enum class Kind { EVIDENCE, ENTRY, NO_LONG, MANAGEMENT }",
        "    data class Item(val id: String, val family: String, val title: String, val guidance: String,",
        "                    val kind: Kind, val references: List<String>)",
        "",
        "    val all: List<Item> = listOf(",
    ]
    for item in items:
        refs = "listOf(" + ", ".join(literal(ref) for ref in item["refs"]) + ")" if item["refs"] else "emptyList()"
        lines.append(
            "        Item(" + ", ".join((literal(item["id"]), literal(item["family"]),
                                     literal(item["title"]), literal(item["guidance"]),
                                     "Kind." + item["kind"], refs)) + "),"
        )
    lines += [
        "    )",
        "    val signals: List<Item> = all.take(240)",
        "    val recipes: List<Item> = all.drop(240)",
        "    private val byId: Map<String, Item> by lazy { all.associateBy { it.id } }",
        "    fun find(id: String): Item? = byId[id]",
        "",
        "    /** Rotate across the ten setup families in background research, without hot-path allocation. */",
        "    fun researchBrief(epoch: Long, maxRecipes: Int = 6): String {",
        "        val groups = recipes.groupBy { it.family }.values.toList()",
        "        if (groups.isEmpty()) return \"\"",
        "        val start = ((epoch % groups.size + groups.size) % groups.size).toInt()",
        "        val count = maxRecipes.coerceIn(1, groups.size)",
        "        val lines = (0 until count).map { index ->",
        "            val group = groups[(start + index) % groups.size]",
        "            val pick = ((epoch / groups.size + index) % group.size + group.size) % group.size",
        "            val item = group[pick.toInt()]",
        '            "${item.id} ${item.title}: ${item.guidance.take(500)}"',
        "        }",
        '        return "HANDWRITTEN BIBLE RESEARCH (300 hypotheses, NONE proven or live-authorised):\\n" +',
        '            "Never assume a bullish sign: follow measured age/venue-specific directions and held-out after-cost tests. " +',
        '            "If the full predicate is not expressible from observed data, mark UNKNOWN; do not invent an entry or new gate.\\n" +',
        '            lines.joinToString("\\n")',
        "    }",
        "",
        "    fun statusLine(): String =",
        '        "signalBible300[signals=${signals.size} recipes=${recipes.size} families=${all.map { it.family }.distinct().size} " +',
        '            "liveAuthority=$LIVE_AUTHORITY source=${SOURCE_SHA256.take(12)}]"',
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if the generated Kotlin disagrees with its Markdown source")
    args = parser.parse_args()
    source = SOURCE.read_text(encoding="utf-8")
    rendered = generate(source, extract(source))
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != rendered:
            raise SystemExit(f"Signal Bible generated source is missing/stale: {OUTPUT}")
    else:
        OUTPUT.write_text(rendered, encoding="utf-8")
    print("Signal Bible validated: 240 signals, 60 setups, 30 families; no live authority")


if __name__ == "__main__":
    main()
